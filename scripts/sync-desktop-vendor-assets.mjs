import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'node_modules', 'katex', 'dist');
const target = join(root, 'public', 'vendor', 'katex');

if (!existsSync(join(source, 'katex.min.js'))) {
  throw new Error('KaTeX distribution is missing; run pnpm install before building');
}

mkdirSync(join(target, 'contrib'), { recursive: true });
for (const file of ['katex.min.css', 'katex.min.js']) {
  cpSync(join(source, file), join(target, file));
}
cpSync(
  join(source, 'contrib', 'auto-render.min.js'),
  join(target, 'contrib', 'auto-render.min.js'),
);
cpSync(join(source, 'fonts'), join(target, 'fonts'), { recursive: true });

console.log('[sync-desktop-vendor-assets] KaTeX assets are available under /vendor/katex');

const desktopFontsTarget = join(root, 'public', 'vendor', 'desktop-fonts');
const desktopFontAliases = [
  {
    family: 'SourceHanSans',
    packageName: 'noto-sans-sc',
    sourceFamily: 'Noto Sans SC',
    weights: [400, 700],
  },
  {
    family: 'SourceHanSerif',
    packageName: 'noto-serif-sc',
    sourceFamily: 'Noto Serif SC',
    weights: [400, 700],
  },
  {
    family: 'LXGWWenKai',
    packageName: 'lxgw-wenkai',
    sourceFamily: 'LXGW WenKai',
    weights: [500, 700],
  },
  {
    family: 'ZhuQueFangSong',
    packageName: 'noto-serif-sc',
    sourceFamily: 'Noto Serif SC',
    weights: [400, 700],
  },
  {
    family: 'WenDingPLKaiTi',
    packageName: 'lxgw-wenkai',
    sourceFamily: 'LXGW WenKai',
    weights: [500, 700],
  },
  {
    family: 'ZcoolHappy',
    packageName: 'zcool-kuaile',
    sourceFamily: 'ZCOOL KuaiLe',
    weights: [400],
  },
];

rmSync(desktopFontsTarget, { recursive: true, force: true });
mkdirSync(join(desktopFontsTarget, 'files'), { recursive: true });

const copiedFontFiles = new Set();
const desktopFontCss = desktopFontAliases.flatMap((alias) =>
  alias.weights.map((weight) => {
    const packageRoot = join(root, 'node_modules', '@fontsource', alias.packageName);
    const cssPath = join(packageRoot, `${weight}.css`);
    if (!existsSync(cssPath)) {
      throw new Error(`Desktop font source is missing: ${cssPath}`);
    }

    const css = readFileSync(cssPath, 'utf8')
      .replaceAll(`font-family: '${alias.sourceFamily}';`, `font-family: '${alias.family}';`)
      .replace(
        /src: url\(\.\/files\/([^)]+\.woff2)\) format\('woff2'\), url\(\.\/files\/[^)]+\.woff\) format\('woff'\);/g,
        "src: url('./files/$1') format('woff2');",
      );

    for (const match of css.matchAll(/url\('\.\/files\/([^']+\.woff2)'\)/g)) {
      const fileName = match[1];
      if (!copiedFontFiles.has(fileName)) {
        cpSync(join(packageRoot, 'files', fileName), join(desktopFontsTarget, 'files', fileName));
        copiedFontFiles.add(fileName);
      }
    }

    return `/* ${alias.family}: packaged from @fontsource/${alias.packageName} */\n${css}`;
  }),
);

writeFileSync(
  join(desktopFontsTarget, 'fonts.css'),
  `/* Generated by scripts/sync-desktop-vendor-assets.mjs. */\n${desktopFontCss.join('\n')}`,
);

console.log(
  `[sync-desktop-vendor-assets] ${copiedFontFiles.size} desktop font files are available under /vendor/desktop-fonts`,
);
